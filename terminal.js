    async submit(guess) {
      if (!guess) { line(span("err", "usage: submit flag{...}")); return; }
      if (!(window.crypto && crypto.subtle)) { line(span("err", "flag check needs https")); return; }
      const buf = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(guess.trim()));
      const hex = [...new Uint8Array(buf)].map((b) => b.toString(16).padStart(2, "0")).join("");
      if (hex !== FLAG_SHA256) {
        line(span("err", "✗ flag rejected"), muted(" — "), cmdLink("ctf", "hints"));
        return;
      }
      line(pass("🏴 flag accepted."), " zero trust, but you verified. You'd fit right in.");
      line(muted("let's talk: "), cmdLink("contact"), muted(" · "), cmdLink("terraform apply"));
      emit("flag");
    },

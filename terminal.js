  // cv.md is generated by build_cv2.js in a fixed layout; parseCv reads that layout back into the CV data shape.
  function parseCv(md) {
    const sections = { "": [] };
    let cur = sections[""];
    for (const l of md.replace(/\r\n/g, "\n").split("\n")) {
      const m = l.match(/^## (.+)$/);
      if (m) cur = sections[m[1].trim().toLowerCase()] = [];
      else cur.push(l);
    }
    const kv = (ls) => Object.fromEntries(ls
      .map((l) => l.match(/^- \*\*(.+?):\*\* (.*)$/)).filter(Boolean)
      .map((m) => [m[1], m[2].trim()]));
    const paras = (ls) => ls.join("\n").split(/\n{2,}/).map((p) => p.trim()).filter(Boolean);
    const table = (ls) => ls.filter((l) => l.startsWith("|")).slice(2).map((l) =>
      l.trim().replace(/^\|/, "").replace(/\|$/, "").split(/(?<!\\)\|/).map((c) => c.trim().replace(/\\\|/g, "|")));

    const head = sections[""];
    const name = (head.find((l) => l.startsWith("# ")) || "").slice(2).trim();
    const title = (head.find((l) => l.startsWith("> ")) || "").slice(2).trim();
    const summary = paras(head).find((p) => !/^[#>-]/.test(p)) || "";

    const experience = [];
    let role = null;
    for (const l of sections.experience || []) {
      let m;
      if ((m = l.match(/^### (.+?) @ (.+)$/))) { role = { title: m[1], company: m[2], bullets: [] }; experience.push(role); }
      else if (!role) continue;
      else if ((m = l.match(/^<!-- id: (\S+) -->$/))) role.id = m[1];
      else if ((m = l.match(/^\*(.+?) – (.+?) · (.+)\*$/))) Object.assign(role, { start: m[1], end: m[2], location: m[3] });
      else if ((m = l.match(/^- (.+)$/))) role.bullets.push(m[1]);
    }
    experience.forEach((r) => { r.id = r.id || r.company.toLowerCase().split(/\s/)[0].replace(/[^a-z0-9-]/g, ""); });

    return {
      name, title, summary, ...kv(head), experience,
      skills: table(sections.skills || []).map(([label, items]) => ({ label, items })),
      education: kv(sections.education || []),
      languages: paras(sections.languages || [])[0] || "",
      scan: table(sections["security scan"] || []).map(([check, target, result]) => ({ check, target, result })),
    };
  }

